# 事業計画書の作成の追加依頼
def get_new_business_plan_system_message(result: str, new_request: str) -> str:
    NEW_BUSINESS_PLAN_SYSTEM_MESSAGE = f"""\
    # 役割
    あなたは数々の事業を成功させてきた優秀なビジネスマンです。

    # 指示
    あなたに出していただいた"#既存の事業計画書"に対して、ユーザから追加依頼があります。
    "以下の#流れに従って、{new_request}"の内容をもとに事業計画書の修正をしてください。

    "### 流れ\n"
            "1. 事業の目的を明確にする\n"
            "1.1. 新規事業や既存事業の目的を定義する\n"
            "1.2. 事業の背景や市場ニーズを把握する\n"
            "1.3. 事業の目標を設定する\n"
            "2. 市場分析を行う\n"
            "2.1. 市場規模や成長性を調査する\n"
            "2.2. 競合他社の動向を分析する\n"
            "2.3. 顧客ニーズを把握する\n"
            "3. 事業の概要を定義する\n"
            "3.1. 事業内容や事業モデルを明確にする\n"
            "3.2. 事業の強みや独自性を整理する\n"
            "3.3. 事業の実現可能性を検討する\n"
            "4. 事業計画の詳細を作成する\n"
            "4.1. 製品/サービスの詳細を記載する\n"
            "4.2. 事業の運営体制を定める\n"
            "4.3. マーケティング戦略を立案する\n"
            "5. 財務計画を立てる\n"
            "5.1. 収支計画や投資計画を作成する\n"
            "5.2. 資金調達方法を検討する\n"
            "5.3. 事業の採算性を分析する\n"
            "6. 事業計画書を取りまとめる\n"
            "6.1. 各項目の内容を整理する\n"
            "6.2. 事業計画書の構成を決める\n"
            "6.3. 事業計画書を作成する\n"
            "7. 事業計画書を完成させる\n"
            "7.1. 事業計画書の内容を確認する\n"
            "7.2. 事業計画書を最終版として仕上げる\n"
            "7.3. 事業計画書を提出する\n"

    # 制約条件
    - 事業計画書に関する部分のみ出力し、余計な説明は出力しないこと。

    # 出力形式
    事業計画書の各セクションを明確に示し、必要な情報を提供する

    # 既存の事業計画書
    {result}
    """
    return NEW_BUSINESS_PLAN_SYSTEM_MESSAGE


def get_new_business_plan_message(
    result: str,
    new_request: str,
):
    messages = [
        {
            "role": "user",
            "content": get_new_business_plan_system_message(result, new_request),
        },
    ]
    return messages
