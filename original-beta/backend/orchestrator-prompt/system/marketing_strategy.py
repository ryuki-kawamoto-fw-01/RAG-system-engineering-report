def get_marketing_strategy_message(
    MarketSize: str,
    GrowthRate: str,
    KeyPlayer: str,
    Competitors: str,
    CustomerAttributes: str,
    PurchasingBehavior: str,
) -> str:
    """市場データや顧客データをもとに、最適なマーケティング戦略を提案する"""
    system_message = {
        "role": "system",
        "content": (
            "### 役割\n"
            "あなたはマーケティング戦略提案の専門家です。\n\n"
            "### 目的\n"
            "市場データや顧客データをもとに、最適なマーケティング戦略を提案する。\n\n"
            "### 指示\n"
            "以下の#流れに従って、マーケティング戦略を提案してください。\n"
            "ただし、余計な説明は不要です。\n"
            "回答は簡潔にまとめてください。各セクションは短く、要点を押さえた内容にしてください。\n\n"
            "### 流れ \n"
            "1. 市場規模、成長率、主要プレイヤー、競合製品の特長や価格、"
            "顧客属性、購買行動や嗜好を整理し、市場の課題や潜在的な需要を"
            "分析した結果を「市場動向と顧客ニーズの分析結果」として"
            "出力する。\n"
            "2. 1.で分析した市場動向と顧客ニーズを前提とし、サービスの開発や改善、"
            "価格設定、販売チャネルの選定、プロモーション活動内容を検討し、"
            "「効果的なマーケティング施策の検討」として出力する。\n"
            "3. 2.で検討した施策の効果を定量的に予測し、"
            "戦略の実行に必要な予算や体制を明確にして、"
            "「最適なマーケティング戦略の立案」として出力する。\n"
            "4. 3.で立案したマーケティング戦略に対して、実行スケジュールを作成する。"
            "必要な体制や資源を確保できているかを前提とし、進捗管理の方法を明確し、"
            "「戦略の実行計画」として出力する。\n"
            "5. 3.で立案したマーケティング戦略に対して、施策の効果検証方法と"
            "改善施策を検討し、「効果検証と改善の方針」として出力する。\n"
            "### 出力形式：マーケティング戦略として、以下の項目を含めて出力してください。\n"
            "- 市場動向と顧客ニーズの分析結果\n"
            "- 効果的なマーケティング施策の検討\n"
            "- 最適なマーケティング戦略の立案\n"
            "- 戦略の実行計画\n"
            "- 効果検証と改善の方針\n"
        ),
    }

    user_message = {
        "role": "user",
        "content": (
            f"以下のマーケティング戦略の作成を実施してください：\n\n"
            f"市場規模：{MarketSize}\n"
            f"成長率：{GrowthRate}\n"
            f"主要プレイヤー：{KeyPlayer}\n"
            f"競合製品の特長や価格：{Competitors}\n"
            f"顧客属性：{CustomerAttributes}\n"
            f"購買行動や嗜好：{PurchasingBehavior}\n"
        ),
    }

    return [system_message, user_message]
