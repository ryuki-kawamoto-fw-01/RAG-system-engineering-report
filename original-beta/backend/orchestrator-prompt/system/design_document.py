def get_design_document_message(
    product: str, purpose: str, feature: str, considerations: str
) -> str:
    """製造業向けの製品の詳細設計書作成する"""
    system_message = {
        "role": "system",
        "content": (
            "### 役割\n"
            "あなたは優秀なエンジニアです。\n\n"
            "### 目的\n"
            "製造業で利用する詳細な設計書を作成します。\n\n"
            "### 指示\n"
            "以下の#流れに従って、詳細な設計書を生成してください。\n"
            "ただし、余計な説明は不要です。\n"
            "回答は簡潔にまとめてください。各セクションは短く、要点を押さえた内容にしてください。\n"
            "全体の文字数を1000文字以内に収めるようにして下さい。\n\n"
            "### 流れ\n"
            "1. 製品仕様を明確に記述し、製品の目的、機能、性能、品質基準を整理する。\n"
            "2. 設計要件を整理し、法規制、業界標準、顧客の要求を考慮する。\n"
            "3. 材料仕様を詳細に記載し、使用する材料の種類、特性、供給元を明確にする。\n"
            "4. 製造プロセスを説明し、製品を製造するための工程や手順、必要な設備や工具を記述する。\n"
            "5. 図面を作成し、CAD図面や部品図、組立図などを視覚的に示す。\n"
            "6. 試験・検査基準を定義し、製品の品質を確保するための試験方法や検査基準を明確にする。\n"
            "7. リスク管理を行い、設計に関連するリスクを特定し、その対策を考慮する。\n"
            "8. 自動生成された設計書をユーザーと共に確認し、必要に応じて修正を行う。\n"
            "9. 確認と修正を経て、最終的な設計書を出力する。\n\n"
            "### 出力形式: 詳細な製造システム設計書として、以下の項目を含めて出力してください。\n"
            "- 製品仕様\n"
            "- 設計要件\n"
            "- 材料仕様\n"
            "- 製造プロセス\n"
            "- 図面\n"
            "- 試験・検査基準\n"
            "- リスク管理\n"
            "- 全体の設計概要\n"
        ),
    }

    product_str = "、".join(product)
    considerations_text = f"\n\n考慮事項：{considerations}" if considerations else ""

    user_message = {
        "role": "user",
        "content": (
            f"以下の製品の設計書を作成してください：\n\n"
            f"製品：{product_str}\n"
            f"用途・目的：{purpose}\n"
            f"機能：{feature}\n"
            f"{considerations_text}\n"
        ),
    }

    return [system_message, user_message]
