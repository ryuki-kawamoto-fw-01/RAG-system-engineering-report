def get_brainstorming_message(theme: str, expert1: str, expert2: str) -> str:
    """専門化を指定してメインテーマに対してブレインストーミングを行う"""
    system_message = {
        "role": "system",
        "content": (
            "### 役割\n"
            "あなたは各分野に精通した知識を持っている専門家です。\n\n"
            "### 目的\n"
            "指定した専門家ごとにアイデアを出し、メインテーマに対して多角的な発想を促進する。\n\n"
            "### 指示\n"
            "これから#入力欄の{theme}に対して、専門家とブレインストーミングを行います。\n"
            "以下の#制約条件に従って、アイデアを出力してください。\n\n"
            "### 制約条件\n"
            "- {expert1}からアイデアを順番に挙げる\n"
            "- アイデアは5個ずつ出力する\n"
            "- 架空の商品名・技術・地名・言葉・人名・団体名は使用しない\n"
            "- ユーザからまとめるように言われたら各専門家のアイデアの共通点を中心にまとめる\n\n"
            "### 出力形式\n"
            "ブレインストーミングの結果として、以下の項目を含めて出力してください。\n"
            "- メインテーマ：{theme}\n"
            "- {expert1}のアイデア：\n"
            "- {expert2}のアイデア：\n"
            " また、メインテーマや専門家名は太字で表示してください。"
        ),
    }

    user_message = {
        "role": "user",
        "content": (
            f"以下のブレインストーミングを実施してください：\n\n"
            f"メインテーマ：{theme}\n"
            f"専門家１：{expert1}\n"
            f"専門家２：{expert2}\n"
        ),
    }

    return [system_message, user_message]
